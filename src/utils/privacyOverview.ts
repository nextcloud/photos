import { n, t } from '@nextcloud/l10n'
import { tileServerHost } from './mapTiles.ts'

/** Facts reported by the server, see PrivacyOverviewService. */
export type PrivacyOverview = {
	places: { enabled: boolean, source: string }
	recognize: boolean
	ai: { known: boolean, tasks: { name: string, provider: string | null }[] }
	publicLinkAlbums: number
}

/** Where the data of an item is processed. */
export type PrivacyState = 'local' | 'external' | 'on' | 'off' | 'unknown'

export type PrivacyItem = {
	id: 'storage' | 'places' | 'map' | 'recognize' | 'ai' | 'publicLinks'
	title: string
	description: string
	state: PrivacyState
	details: string[]
}

/**
 * Label of a privacy state.
 *
 * @param state - The state to label
 */
export function privacyStateLabel(state: PrivacyState): string {
	switch (state) {
		case 'local':
			return t('photos', 'On this server')
		case 'external':
			return t('photos', 'External service')
		case 'on':
			return t('photos', 'On')
		case 'off':
			return t('photos', 'Off')
		default:
			return t('photos', 'Unknown')
	}
}

/**
 * Describe where photos and their metadata go.
 * Facts the server could not report are shown as unknown.
 *
 * @param overview - Facts reported by the server, null if they could not be loaded
 * @param tileServerUrl - Tile URL template the maps load their tiles from
 */
export function buildPrivacyItems(overview: PrivacyOverview | null, tileServerUrl: string): PrivacyItem[] {
	const unknown = t('photos', 'This could not be determined.')
	const items: PrivacyItem[] = [{
		id: 'storage',
		title: t('photos', 'Photos and previews'),
		description: t('photos', 'Your photos are kept in your Nextcloud files and their previews are generated by this server.'),
		state: 'local',
		details: [],
	}]

	if (overview === null) {
		items.push({ id: 'places', title: t('photos', 'Place names'), description: unknown, state: 'unknown', details: [] })
	} else if (overview.places.enabled) {
		items.push({
			id: 'places',
			title: t('photos', 'Place names'),
			description: t('photos', 'Place names are looked up on this server in a list of cities downloaded from {source}. Photo locations are not sent anywhere.', { source: overview.places.source }, { escape: false }),
			state: 'local',
			details: [],
		})
	} else {
		items.push({
			id: 'places',
			title: t('photos', 'Place names'),
			description: t('photos', 'Place names are not looked up for your photos.'),
			state: 'off',
			details: [],
		})
	}

	items.push({
		id: 'map',
		title: t('photos', 'Maps'),
		description: t('photos', 'Map images are loaded from {host}. That service sees your IP address, the address of this Nextcloud and which areas you look at, which can reveal approximately where your photos were taken.', { host: tileServerHost(tileServerUrl) }, { escape: false }),
		state: 'external',
		details: [],
	})

	if (overview === null) {
		items.push({ id: 'recognize', title: t('photos', 'Face and object recognition'), description: unknown, state: 'unknown', details: [] })
	} else {
		items.push({
			id: 'recognize',
			title: t('photos', 'Face and object recognition'),
			description: overview.recognize
				? t('photos', 'Faces and objects are recognized by the Recognize app on this server.')
				: t('photos', 'The Recognize app is not enabled, faces and objects are not recognized.'),
			state: overview.recognize ? 'local' : 'off',
			details: [],
		})
	}

	if (overview === null || !overview.ai.known) {
		items.push({ id: 'ai', title: t('photos', 'AI services'), description: unknown, state: 'unknown', details: [] })
	} else if (overview.ai.tasks.length === 0) {
		items.push({
			id: 'ai',
			title: t('photos', 'AI services'),
			description: t('photos', 'No AI service of this Nextcloud can process photos or videos.'),
			state: 'off',
			details: [],
		})
	} else {
		items.push({
			id: 'ai',
			title: t('photos', 'AI services'),
			description: t('photos', 'Photos does not send your photos to AI services. Other apps can, when you ask them to. Whether these services run on this server or elsewhere is not reported:'),
			state: 'unknown',
			details: overview.ai.tasks.map(({ name, provider }) => provider
				? t('photos', '{task}, by {provider}', { task: name, provider }, { escape: false })
				: name),
		})
	}

	if (overview === null) {
		items.push({ id: 'publicLinks', title: t('photos', 'Public album links'), description: unknown, state: 'unknown', details: [] })
	} else {
		items.push({
			id: 'publicLinks',
			title: t('photos', 'Public album links'),
			description: overview.publicLinkAlbums > 0
				? n('photos', '%n album can be opened by anyone who has its link.', '%n albums can be opened by anyone who has their link.', overview.publicLinkAlbums)
				: t('photos', 'None of your albums is shared by a public link.'),
			state: overview.publicLinkAlbums > 0 ? 'on' : 'off',
			details: [],
		})
	}

	return items
}
